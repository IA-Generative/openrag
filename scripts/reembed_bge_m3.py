def _names(collection: str) -> tuple[str, str, str]:
    return f"{collection}{REBUILD_SUFFIX}", f"{collection}{BACKUP_SUFFIX}", f"{collection}{ROLLBACK_ASIDE_SUFFIX}"


def _vector_dim(helpers: ModuleType, client: Any, collection: str) -> int:
    return helpers._vector_dim(client.describe_collection(collection))


def _check_is_ours(helpers: ModuleType, client: Any, target: str, model: str) -> None:
    desc = client.describe_collection(target)
    built_with = desc.get("properties", {}).get(REEMBED_MODEL_PROPERTY)
    dim = helpers._vector_dim(desc)
    if built_with != model or dim != TARGET_DIM:
        raise ReembedError(
            f"Collection '{target}' exists but was not built by this tool for '{model}' "
            f"(marker={built_with!r}, dim={dim}). Inspect it and drop it before retrying."
        )


def _allow_explicit_ids(helpers: ModuleType, client: Any, target: str) -> None:
    """(Re)open the target to rows that carry their own ``_id``. Idempotent.

    ``finalize`` closes it just before the swap; if the swap then fails, the
    next run must be able to insert its catch-up rows again.
    """
    client.alter_collection_properties(target, properties={helpers.ALLOW_INSERT_AUTO_ID: "true"})


def _create_target(helpers: ModuleType, client: Any, source: str, target: str, model: str) -> None:
    source_desc = client.describe_collection(source)
    target_shape = _with_vector_dim(source_desc, TARGET_DIM)
    client.create_collection(
        collection_name=target,
        schema=helpers._build_v2_schema(client, target_shape),
        consistency_level="Strong",
        index_params=helpers._build_v2_index_params(client, target_shape),
        enable_dynamic_field=True,
    )
    helpers._assert_no_field_loss(source_desc, client.describe_collection(target))
    client.alter_collection_properties(
        target, properties={helpers.ALLOW_INSERT_AUTO_ID: "true", REEMBED_MODEL_PROPERTY: model}
    )
    logger.info(f"Created '{target}' (dim={TARGET_DIM}, model marker '{model}').")


def build(
    client: Any,
    helpers: ModuleType,
    embedder: GatewayEmbedder | None,
    collection: str,
    model: str,
    *,
    dry_run: bool = False,
) -> Plan:
    target, backup, _ = _names(collection)
    if client.has_collection(backup):
        raise ReembedError(f"'{backup}' already exists — this collection was already swapped. Nothing to build.")
    exists = client.has_collection(target)
    if exists:
        _check_is_ours(helpers, client, target, model)
        if not dry_run:
            _allow_explicit_ids(helpers, client, target)
    elif not dry_run:
        _create_target(helpers, client, collection, target, model)
        exists = True
    plan = reconcile(client, helpers, embedder, collection, target if exists else None, dry_run=dry_run)
    if dry_run:
        logger.info("[DRY-RUN] No changes were made.")
    return plan


def _cosine(a: list[float], b: list[float]) -> float:
    norm = math.sqrt(sum(x * x for x in a)) * math.sqrt(sum(y * y for y in b))
    return sum(x * y for x, y in zip(a, b, strict=True)) / norm if norm else 0.0


def _verify_sample(client: Any, embedder: GatewayEmbedder, target: str, ids: list[int], size: int) -> None:
    """Re-embed a spread of rows and compare with what the target stores.

    Counts and fingerprints prove the right rows are there; only this proves
    each row carries *its own* vector rather than a neighbour's.
    """
    if size <= 0 or not ids:
        return
    step = max(1, len(ids) // size)
    sample = ids[::step][:size]
    rows = _fetch(client, target, sample, ["_id", "text", "vector"])
    ordered = [rid for rid in sample if rid in rows]
    fresh = embedder.embed([rows[rid].get("text") or "" for rid in ordered])
    worst = min((_cosine(rows[rid]["vector"], vec), rid) for rid, vec in zip(ordered, fresh, strict=True))
    logger.info(f"Sample check: {len(ordered)} rows re-embedded, lowest cosine {worst[0]:.4f} (_id {worst[1]}).")
    if worst[0] < _SAMPLE_MIN_COSINE:
        raise ReembedError(
            f"Row {worst[1]} of '{target}' does not match its own text (cosine {worst[0]:.4f}). "
            "The target collection is not trustworthy — do not swap."
        )


def _wait_for_indexes(
    client: Any, collection: str, *, timeout: float = 900.0, sleep: Callable[[float], None] = time.sleep
) -> None:
    """Best effort: let the index build catch up before the collection goes live."""
    waited = 0.0
    try:
        while waited < timeout:
            pending = sum(
                int(client.describe_index(collection, name).get("pending_index_rows", 0))
                for name in client.list_indexes(collection)
            )
            if pending == 0:
                return
            logger.info(f"  waiting for indexes on '{collection}': {pending} rows pending")
            sleep(10.0)
            waited += 10.0
        logger.warning(
            f"Indexes on '{collection}' still building after {timeout:.0f}s — searches stay correct, only slower."
        )
    except Exception as exc:  # noqa: BLE001 — never fail a verified rebuild over an index probe
        logger.warning(f"Could not check index progress on '{collection}' ({exc}).")


def finalize(
    client: Any,
    helpers: ModuleType,
    embedder: GatewayEmbedder | None,
    collection: str,
    model: str,
    *,
    dry_run: bool = False,
    sample_size: int = 32,
) -> None:
    target, backup, _ = _names(collection)
    if not client.has_collection(target):
        raise ReembedError(f"'{target}' does not exist — run `build` first.")
    if client.has_collection(backup):
        raise ReembedError(f"'{backup}' already exists — inspect and drop it before finalizing.")
    _check_is_ours(helpers, client, target, model)

    if dry_run:
        plan = reconcile(client, helpers, None, collection, target, dry_run=True)
        logger.info(f"[DRY-RUN] Would apply the plan above, verify, and swap '{target}' into '{collection}'.")
        logger.info(f"[DRY-RUN] Rows left to embed during the window: {len(plan.to_embed)}. No changes were made.")
        return
    if embedder is None:
        raise ReembedError("finalize needs an embedder.")

    _allow_explicit_ids(helpers, client, target)
    count_before = helpers._row_count(client, collection)
    reconcile(client, helpers, embedder, collection, target)
    check = reconcile(client, helpers, None, collection, target, dry_run=True)
    count_after = helpers._row_count(client, collection)
    target_count = helpers._row_count(client, target)

    if count_after != count_before:
        raise ReembedError(
            f"The source changed during finalize: {count_before} rows before, {count_after} after. "
            f"Something is still writing to '{collection}' — stop OpenRAG and run finalize again."
        )
    if not check.empty:
        raise ReembedError(
            f"Source and target still differ after the catch-up ({check.summary()}). Stop OpenRAG and retry."
        )
    if target_count != count_after:
        raise ReembedError(f"Row-count mismatch: source={count_after}, target={target_count}. Nothing was swapped.")
    if check.source.per_partition != check.target.per_partition:
        raise ReembedError("Per-partition row counts differ between source and target. Nothing was swapped.")
    if _vector_dim(helpers, client, target) != TARGET_DIM:
        raise ReembedError(f"'{target}' is not a {TARGET_DIM}-dimension collection. Nothing was swapped.")
    _verify_sample(client, embedder, target, sorted(check.target.fingerprints), sample_size)
    logger.info(
        f"Verified: {target_count} rows, {len(check.target.per_partition)} partitions, same _id set and fields."
    )

    _wait_for_indexes(client, target)
    # Same schema as the source, so the same version stamp: the application
    # refuses a collection whose stamp differs from the one its build expects.
    client.drop_collection_properties(target, property_keys=[helpers.ALLOW_INSERT_AUTO_ID])
    helpers._stamp_version(client, target, helpers._get_stored_version(client, collection))

    helpers._swap_collections(client, collection, target, backup)
    # Past this line the swap is done: nothing below may turn it into a
    # reported failure, or the caller would roll the embedder back under a
    # collection that has already changed width.
    helpers._release(client, backup)
    try:
        client.load_collection(collection)
    except Exception as exc:  # noqa: BLE001 — the application loads the collection itself at startup
        logger.warning(f"Could not load '{collection}' after the swap ({exc}); OpenRAG loads it on startup.")
    logger.info(
        f"Done. '{collection}' now holds {TARGET_DIM}-dimension '{model}' vectors.\n"
        f"  The previous collection is kept as '{backup}' — drop it once validated.\n"
        "  Switch the embedder (DB record AND environment) before starting OpenRAG."
    )


def rollback(client: Any, helpers: ModuleType, collection: str, *, dry_run: bool = False) -> None:
    _, backup, aside = _names(collection)
    if not client.has_collection(backup):
        raise ReembedError(f"No backup collection '{backup}' — nothing to roll back to.")
    if client.has_collection(aside):
        raise ReembedError(f"Collection '{aside}' already exists — inspect and drop it before rolling back.")
    logger.info(
        f"{'[DRY-RUN] ' if dry_run else ''}Rolling back:\n"
        f"  '{collection}' → '{aside}' (kept aside)\n"
        f"  '{backup}' → '{collection}' (restored)"
    )
    if dry_run:
        logger.info("[DRY-RUN] No changes were made.")
        return
    helpers._swap_collections(client, collection, backup, aside)
    helpers._release(client, aside)
    client.load_collection(collection)
    logger.warning(
        f"Rollback complete. Rows indexed after the swap remain only in '{aside}'. "
        "Switch the embedder back (DB record AND environment) before starting OpenRAG."
    )


