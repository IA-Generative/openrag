def _load_rebuild_helpers() -> ModuleType:
    """Import ``2.rebuild_text_analyzer.py`` the way the migration runner does."""
    import services.persistence.migrations.milvus as milvus_migrations

    path = Path(milvus_migrations.__file__).resolve().parent / "2.rebuild_text_analyzer.py"
    spec = importlib.util.spec_from_file_location("milvus_migration_v2", path)
    if spec is None or spec.loader is None:
        raise ReembedError(f"Cannot load the rebuild helpers from {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _with_vector_dim(desc: dict[str, Any], dim: int) -> dict[str, Any]:
    """The source description with only the ``vector`` dimension replaced."""
    out = copy.deepcopy(desc)
    for f in out.get("fields", []):
        if f["name"] == "vector":
            f.setdefault("params", {})["dim"] = dim
            return out
    raise ReembedError("Collection has no `vector` field — not an OpenRAG collection.")


def _scalar_output_fields(desc: dict[str, Any]) -> list[str]:
    """Every declared field but the vectors, plus the dynamic ones (``$meta``)."""
    return [f["name"] for f in desc.get("fields", []) if f["name"] not in _VECTOR_KEYS] + ["$meta"]


