TARGET_DIM = 1024

REBUILD_SUFFIX = "_bge_m3_rebuild"
BACKUP_SUFFIX = "_gemma2_backup"
ROLLBACK_ASIDE_SUFFIX = "_bge_m3_rolled_back"

#: Marks a collection as built by this tool, so ``build`` never adopts — and
#: never writes into — a collection that merely happens to carry the name.
REEMBED_MODEL_PROPERTY = "openrag.reembed_model"

#: Never written back (``sparse`` is generated by Milvus) or never part of a
#: row's identity (``vector`` is the very thing being replaced).
_VECTOR_KEYS = frozenset({"vector", "sparse"})

#: Texts per embedding request.
EMBED_BATCH = 32

#: Rows per ``_id in [...]`` fetch / delete.
ID_BATCH = 500

#: Requests per minute the tool allows itself. The key is shared with the
#: running application (LLM, reranker): using the whole quota for a bulk job
#: would turn into 429s for users.
DEFAULT_MAX_RPM = 120

#: Cap on a single wait, whatever ``Retry-After`` says.
_MAX_WAIT_SECONDS = 300.0

_RETRYABLE_STATUS = frozenset({429, 500, 502, 503, 504})

#: Cosine under which a re-embedded sample row counts as not matching the
#: vector stored in the target. The same text through the same model lands at
#: 0.999+; a vector attached to the wrong row lands far below.
_SAMPLE_MIN_COSINE = 0.99

#: Exit codes. ``EXIT_REFUSED``: the tool stopped before changing anything that
#: matters — the live collection is as it was. ``EXIT_UNKNOWN_STATE``: something
#: unexpected broke; a wrapper must not restart the application on its own.
EXIT_REFUSED = 1
EXIT_UNKNOWN_STATE = 2

logger = get_logger()


class ReembedError(RuntimeError):
    """Raised for every condition that must stop the tool before it writes."""


