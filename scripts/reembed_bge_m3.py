def _digest(value: str) -> bytes:
    return hashlib.sha256(value.encode("utf-8")).digest()


def _normalise(value: Any) -> Any:
    return value.isoformat() if isinstance(value, datetime) else value


def _fingerprint(row: dict[str, Any]) -> bytes:
    """Identity of a row: every field but the vectors."""
    payload = {k: _normalise(v) for k, v in row.items() if k not in _VECTOR_KEYS}
    return _digest(json.dumps(payload, sort_keys=True, ensure_ascii=False, default=str))


@dataclass
class _Snapshot:
    """What one full scan of a collection retains: two hashes per row."""

    fingerprints: dict[int, bytes] = field(default_factory=dict)
    text_digests: dict[int, bytes] = field(default_factory=dict)
    per_partition: Counter = field(default_factory=Counter)


@dataclass
class Plan:
    """The difference between source and target, as three disjoint ``_id`` lists."""

    to_embed: list[int]  # missing from the target, or present with another text
    to_patch: list[int]  # same text, other fields changed — the new vector is kept
    to_delete: list[int]  # gone from the source
    stale: list[int]  # subset of to_embed already in the target, to remove first
    source: _Snapshot
    target: _Snapshot

    @property
    def empty(self) -> bool:
        return not (self.to_embed or self.to_patch or self.to_delete)

    def summary(self) -> str:
        return (
            f"source={len(self.source.fingerprints)} rows, target={len(self.target.fingerprints)} rows — "
            f"to embed: {len(self.to_embed)}, to patch: {len(self.to_patch)}, to delete: {len(self.to_delete)}"
        )


def _scan(client: Any, collection: str, fields: list[str], page: int) -> _Snapshot:
    snapshot = _Snapshot()
    client.load_collection(collection)
    iterator = client.query_iterator(collection_name=collection, filter="", batch_size=page, output_fields=fields)
    try:
        while True:
            batch = iterator.next()
            if not batch:
                break
            for raw in batch:
                row = dict(raw)
                rid = row["_id"]
                snapshot.fingerprints[rid] = _fingerprint(row)
                snapshot.text_digests[rid] = _digest(row.get("text") or "")
                snapshot.per_partition[row.get("partition")] += 1
    finally:
        iterator.close()
    return snapshot


def _plan(source: _Snapshot, target: _Snapshot) -> Plan:
    to_embed, to_patch, stale = [], [], []
    for rid, fingerprint in source.fingerprints.items():
        if rid not in target.fingerprints:
            to_embed.append(rid)
        elif source.text_digests[rid] != target.text_digests[rid]:
            to_embed.append(rid)
            stale.append(rid)
        elif fingerprint != target.fingerprints[rid]:
            to_patch.append(rid)
    to_delete = [rid for rid in target.fingerprints if rid not in source.fingerprints]
    return Plan(sorted(to_embed), sorted(to_patch), sorted(to_delete), sorted(stale), source, target)


def _batches(ids: list[int], size: int) -> Iterator[list[int]]:
    for start in range(0, len(ids), size):
        yield ids[start : start + size]


def _fetch(client: Any, collection: str, ids: list[int], fields: list[str]) -> dict[int, dict[str, Any]]:
    rows = client.query(collection_name=collection, filter=f"_id in {ids}", output_fields=fields)
    return {dict(r)["_id"]: dict(r) for r in rows}


def _delete(client: Any, collection: str, ids: Iterable[int]) -> None:
    for batch in _batches(list(ids), ID_BATCH):
        client.delete(collection_name=collection, filter=f"_id in {batch}")


def reconcile(
    client: Any,
    helpers: ModuleType,
    embedder: GatewayEmbedder | None,
    source: str,
    target: str | None,
    *,
    dry_run: bool = False,
) -> Plan:
    """Make ``target`` hold exactly the rows of ``source``, re-embedded.

    ``target=None`` plans against an empty target (nothing built yet). The
    source is only ever read.
    """
    desc = client.describe_collection(source)
    fields = _scalar_output_fields(desc)
    page = helpers._copy_batch_size(desc)

    source_snapshot = _scan(client, source, fields, page)
    target_snapshot = _scan(client, target, fields, page) if target else _Snapshot()
    plan = _plan(source_snapshot, target_snapshot)
    logger.info(f"Reconcile plan: {plan.summary()}")
    if dry_run or plan.empty:
        return plan
    if target is None or embedder is None:
        raise ReembedError("reconcile needs a target collection and an embedder to apply a plan.")

    _delete(client, target, plan.to_delete + plan.stale)

    done = 0
    for ids in _batches(plan.to_embed, min(ID_BATCH, page)):
        rows = _fetch(client, source, ids, fields)
        # A row deleted since the scan is simply gone: the next reconcile agrees.
        present = [rid for rid in ids if rid in rows]
        vectors = embedder.embed([rows[rid].get("text") or "" for rid in present])
        if len(vectors) != len(present):
            raise ReembedError(f"{len(vectors)} vectors for {len(present)} rows — refusing to insert.")
        payload = []
        for rid, vector in zip(present, vectors, strict=True):
            row = helpers._prepare_row(rows[rid])
            row["vector"] = vector
            payload.append(row)
        if payload:
            client.insert(collection_name=target, data=payload)
        done += len(payload)
        logger.info(f"  embedded {done}/{len(plan.to_embed)} rows ({embedder.requests} requests)")

    for ids in _batches(plan.to_patch, min(ID_BATCH, page)):
        rows = _fetch(client, source, ids, fields)
        vectors = _fetch(client, target, ids, ["_id", "vector"])
        payload = []
        for rid in ids:
            if rid in rows and rid in vectors:
                row = helpers._prepare_row(rows[rid])
                row["vector"] = vectors[rid]["vector"]
                payload.append(row)
        _delete(client, target, [row["_id"] for row in payload])
        if payload:
            client.insert(collection_name=target, data=payload)
    if plan.to_patch:
        logger.info(f"  patched {len(plan.to_patch)} rows (fields changed, text unchanged — vector kept)")

    client.flush(target)
    return plan


