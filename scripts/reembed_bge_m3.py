def _model_from_env() -> str:
    model = os.environ.get("REEMBED_MODEL")
    if not model:
        raise ReembedError("Missing environment variable: REEMBED_MODEL")
    return model


def _embedder_from_env(model: str, max_rpm: int) -> GatewayEmbedder:
    missing = [k for k in ("REEMBED_BASE_URL", "REEMBED_API_KEY") if not os.environ.get(k)]
    if missing:
        raise ReembedError(f"Missing environment variable(s): {', '.join(missing)}")
    return GatewayEmbedder(os.environ["REEMBED_BASE_URL"], model, os.environ["REEMBED_API_KEY"], max_rpm=max_rpm)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Re-embed a whole Milvus collection with another embedding model.")
    parser.add_argument("command", choices=["build", "status", "finalize", "rollback"])
    parser.add_argument("--dry-run", action="store_true", help="Inspect only, make no changes")
    parser.add_argument(
        "--max-rpm", type=int, default=DEFAULT_MAX_RPM, help="Embedding requests per minute (0 = unpaced)"
    )
    parser.add_argument("--sample", type=int, default=32, help="Rows re-embedded by finalize to verify the target")
    args = parser.parse_args(argv)

    from core.config import load_config
    from pymilvus import MilvusClient

    cfg = load_config()
    collection = cfg.vectordb.collection_name
    client = MilvusClient(uri=f"http://{cfg.vectordb.host}:{cfg.vectordb.port}")
    helpers = _load_rebuild_helpers()

    try:
        if args.command == "rollback":
            rollback(client, helpers, collection, dry_run=args.dry_run)
            return 0
        if not client.has_collection(collection):
            raise ReembedError(f"Collection '{collection}' does not exist.")
        model = _model_from_env()
        # Inspecting needs no key: only a run that embeds does.
        if args.command == "status" or args.dry_run:
            if args.command == "finalize":
                finalize(client, helpers, None, collection, model, dry_run=True)
            else:
                build(client, helpers, None, collection, model, dry_run=True)
            return 0
        embedder = _embedder_from_env(model, args.max_rpm)
        if args.command == "build":
            build(client, helpers, embedder, collection, model)
        else:
            finalize(client, helpers, embedder, collection, model, sample_size=args.sample)
    except ReembedError as exc:
        logger.error(str(exc))
        return EXIT_REFUSED
    except Exception as exc:  # noqa: BLE001 — the caller must tell "refused" from "state unknown"
        logger.exception(f"Unexpected failure: {exc}")
        logger.error(
            f"The state of '{collection}' is NOT known. Check that it still exists before starting OpenRAG: "
            "an application started without it creates an empty one under the same name."
        )
        return EXIT_UNKNOWN_STATE
    return 0


if __name__ == "__main__":
    sys.exit(main())
