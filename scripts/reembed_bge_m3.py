"""
Re-embed a whole Milvus collection with another embedding model
===============================================================
Deployment-specific operational tool, NOT a schema migration: it lives in
``scripts/`` on purpose. A numbered file under
``services/persistence/migrations/milvus/`` would become the default target of
the generic runner for every deployment, and a new schema-version stamp would
make ``MilvusVectorStore._check_schema_version`` refuse the collection. The
collection this tool produces keeps the *same* schema version as its source.

Why: the dense ``vector`` field has a fixed dimension and one collection holds
every partition, so moving from one embedder to another of a different width
(here ``bge-multilingual-gemma2``, 3584 → ``bge-m3``, 1024) means building a new
collection next to the live one and swapping the names.

It reuses the rebuild machinery of ``2.rebuild_text_analyzer.py`` (schema,
indexes, ``_id`` preservation through ``allow_insert_auto_id``, server-side
BM25 regeneration, name swap, release of the collection left aside). The one
difference: the dense vector is **recomputed from ``text``** — which is exactly
the string that was embedded at indexing time — instead of being copied.

Everything goes through one idempotent step, :func:`reconcile`, which makes the
target collection equal to the source (same ``_id`` set, same fields). That one
step is the initial build, the resume after an interruption, and the catch-up:

* ``build``     create the target if needed and reconcile. Read-only on the
                source, so it can run **while OpenRAG is serving**; re-run it
                as often as needed — rows already embedded are not embedded
                again.
* ``status``    show what a reconcile would do. Changes nothing.
* ``finalize``  OpenRAG must be **stopped**. Reconcile one last time, verify
                (source unchanged, nothing left to do, same counts per
                partition, target dimension, re-embedded sample matches),
                then swap the names. The old collection is kept as
                ``<collection>_gemma2_backup`` and released from memory.
* ``rollback``  swap the backup back. Point-in-time: rows indexed after the
                swap live only in the collection moved aside.

Configuration comes from the environment, never from the command line, so the
key cannot end up in a process listing or a shell history:

    REEMBED_BASE_URL   e.g. https://gateway.example/v1
    REEMBED_MODEL      e.g. bge-m3
    REEMBED_API_KEY    bearer token

Usage (inside the application container, as the application user):
    python /app/scripts/reembed_bge_m3.py build [--dry-run] [--max-rpm 120]
    python /app/scripts/reembed_bge_m3.py status
    python /app/scripts/reembed_bge_m3.py finalize [--dry-run]
    python /app/scripts/reembed_bge_m3.py rollback [--dry-run]
"""

