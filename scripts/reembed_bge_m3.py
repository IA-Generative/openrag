class GatewayEmbedder:
    """Minimal OpenAI-compatible ``/embeddings`` client for a bulk job.

    Not the application's ``VLLMEmbedder``: that one ignores ``Retry-After``
    and sits behind a circuit breaker meant for interactive traffic.
    """

    def __init__(
        self,
        base_url: str,
        model: str,
        api_key: str,
        *,
        dim: int = TARGET_DIM,
        max_rpm: int = DEFAULT_MAX_RPM,
        max_attempts: int = 8,
        http: Any | None = None,
        sleep: Callable[[float], None] = time.sleep,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        self._url = base_url.rstrip("/") + "/embeddings"
        self._model = model
        self._dim = dim
        self._min_interval = 60.0 / max_rpm if max_rpm > 0 else 0.0
        self._max_attempts = max_attempts
        self._http = http or httpx.Client(timeout=180.0, headers={"Authorization": f"Bearer {api_key}"})
        self._sleep = sleep
        self._clock = clock
        self._last_request: float | None = None
        self.requests = 0
        self.texts = 0

    def embed(self, texts: list[str]) -> list[list[float]]:
        """Embed ``texts``. One vector per text, in order, or an exception."""
        out: list[list[float]] = []
        for start in range(0, len(texts), EMBED_BATCH):
            out.extend(self._embed_batch(texts[start : start + EMBED_BATCH]))
        return out

    def _pace(self) -> None:
        if self._last_request is not None and self._min_interval:
            wait = self._min_interval - (self._clock() - self._last_request)
            if wait > 0:
                self._sleep(wait)
        self._last_request = self._clock()

    def _embed_batch(self, batch: list[str]) -> list[list[float]]:
        last = "no attempt made"
        for attempt in range(self._max_attempts):
            self._pace()
            self.requests += 1
            try:
                response = self._http.post(self._url, json={"model": self._model, "input": batch})
            except httpx.TransportError as exc:
                last = f"{type(exc).__name__}: {exc}"
                self._sleep(min(2.0**attempt, _MAX_WAIT_SECONDS))
                continue
            if response.status_code in _RETRYABLE_STATUS:
                last = f"HTTP {response.status_code}"
                wait = _retry_after_seconds(response.headers.get("Retry-After"), default=2.0**attempt)
                logger.warning(f"  embedding endpoint answered {last}; waiting {wait:.0f}s")
                self._sleep(wait)
                continue
            if response.status_code != 200:
                raise ReembedError(f"Embedding endpoint answered HTTP {response.status_code}: {response.text[:300]}")
            return self._vectors(response.json(), len(batch))
        raise ReembedError(f"Embedding endpoint still failing after {self._max_attempts} attempts ({last}).")

    def _vectors(self, body: dict[str, Any], expected: int) -> list[list[float]]:
        data = sorted(body.get("data", []), key=lambda d: d["index"])
        if len(data) != expected:
            raise ReembedError(f"Embedding endpoint returned {len(data)} vectors for {expected} texts.")
        vectors = [d["embedding"] for d in data]
        wrong = {len(v) for v in vectors} - {self._dim}
        if wrong:
            raise ReembedError(f"Embedding endpoint returned dimension(s) {sorted(wrong)}, expected {self._dim}.")
        self.texts += expected
        return vectors


def _retry_after_seconds(header: str | None, *, default: float) -> float:
    """Seconds to wait from a ``Retry-After`` header (delta-seconds form)."""
    try:
        wait = float(header) if header is not None else default
    except ValueError:
        wait = default
    return max(0.0, min(wait, _MAX_WAIT_SECONDS))


